#Escreva um programa que peça um número correspondente ao dia da semana (1 para Domingo, 2 para Segunda, etc.)
# e retorne o nome do dia por extenso usando elif.

dia_da_semana = int(input('numero dia da semana: '))

if dia_da_semana == 1:
    print(f'Domingo')
elif dia_da_semana == 2:
    print(f'Segunda')
elif dia_da_semana == 3:
    print(f'Terça')
elif dia_da_semana == 4:
    print(f'Quarta')
elif dia_da_semana == 5:
    print(f'Quinta')
elif dia_da_semana == 6:
    print(f'Sexta')
else:
    print(f'Sabado')




