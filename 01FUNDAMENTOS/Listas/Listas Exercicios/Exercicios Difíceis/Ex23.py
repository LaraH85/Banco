# Uma fábrica mede o diâmetro de peças industriais em uma lista:
# [10.2, 9.8, 10.5, 11.0, 9.9].
# Exiba a amplitude das medidas (a diferença entre a maior peça
# e a menor peça) usando funções embutidas.

controles = [10.2, 9.8, 10.5, 11.0, 9.9]

